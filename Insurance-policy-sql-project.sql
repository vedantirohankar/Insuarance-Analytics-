#QUESTION 19 AVERAGE PREMIUM GROWTH RATE
SELECT
    YEAR(PolicyStartDate) AS PolicyYear,
    SUM(PremiumAmount) AS TotalPremium
FROM POLICYDETAILS
GROUP BY YEAR(PolicyStartDate)
ORDER BY PolicyYear;
 
 WITH YearlyPremium AS (
    SELECT
        YEAR(STR_TO_DATE(PolicyStartDate, '%d-%m-%Y')) AS PolicyYear,
        SUM(PremiumAmount) AS TotalPremium
    FROM POLICYDETAILS
    WHERE STR_TO_DATE(PolicyStartDate, '%d-%m-%Y') IS NOT NULL
    GROUP BY YEAR(STR_TO_DATE(PolicyStartDate, '%d-%m-%Y'))
),
PremiumGrowth AS (
    SELECT
        PolicyYear,
        (
            (TotalPremium - LAG(TotalPremium) OVER (ORDER BY PolicyYear))
            / NULLIF(LAG(TotalPremium) OVER (ORDER BY PolicyYear), 0)
        ) * 100 AS GrowthRate
    FROM YearlyPremium
)
SELECT ROUND(AVG(GrowthRate), 2) AS Average_Premium_Growth_Rate
FROM PremiumGrowth
WHERE GrowthRate IS NOT NULL;

#QUESTION 20 PREMIUM GROWTH TREND
WITH YearlyPremium AS (
    SELECT
        YEAR(STR_TO_DATE(PolicyStartDate, '%d-%m-%Y')) AS PolicyYear,
        SUM(PremiumAmount) AS TotalPremium
    FROM POLICYDETAILS
    WHERE STR_TO_DATE(PolicyStartDate, '%d-%m-%Y') IS NOT NULL
    GROUP BY YEAR(STR_TO_DATE(PolicyStartDate, '%d-%m-%Y'))
)
SELECT
    PolicyYear,
    ROUND(
        (TotalPremium - LAG(TotalPremium) OVER (ORDER BY PolicyYear))
        / NULLIF(LAG(TotalPremium) OVER (ORDER BY PolicyYear), 0) * 100,
        2
    ) AS GrowthRatePercent
FROM YearlyPremium
ORDER BY PolicyYear;

#QUESTION 21 DIFFERENCE B/W HIGHEST AND LOWEST PREMIUM GROWTH RATES
WITH YearlyPremium AS (
    SELECT
        YEAR(STR_TO_DATE(PolicyStartDate, '%d-%m-%Y')) AS PolicyYear,
        SUM(PremiumAmount) AS TotalPremium
    FROM POLICYDETAILS
    WHERE STR_TO_DATE(PolicyStartDate, '%d-%m-%Y') IS NOT NULL
    GROUP BY YEAR(STR_TO_DATE(PolicyStartDate, '%d-%m-%Y'))
),
PremiumGrowth AS (
    SELECT
        PolicyYear,
        (
            (TotalPremium - LAG(TotalPremium) OVER (ORDER BY PolicyYear))
            / NULLIF(LAG(TotalPremium) OVER (ORDER BY PolicyYear), 0)
        ) * 100 AS GrowthRate
    FROM YearlyPremium
)
SELECT
    ROUND(MAX(GrowthRate), 2) AS Highest_Growth_Rate,
    ROUND(MIN(GrowthRate), 2) AS Lowest_Growth_Rate,
    ROUND(MAX(GrowthRate) - MIN(GrowthRate), 2) AS Growth_Rate_Difference
FROM PremiumGrowth
WHERE GrowthRate IS NOT NULL;

#QUESTION 22 YEARLY TREND OF POLICIES FROM 2016 TO 2034
SELECT
    YEAR(STR_TO_DATE(PolicyEndDate, '%d-%m-%Y')) AS EndingYear,
    COUNT(*) AS TotalPoliciesEnding
FROM POLICYDETAILS
WHERE STR_TO_DATE(PolicyEndDate, '%d-%m-%Y') IS NOT NULL
  AND YEAR(STR_TO_DATE(PolicyEndDate, '%d-%m-%Y'))
      BETWEEN 2016 AND 2034
GROUP BY YEAR(STR_TO_DATE(PolicyEndDate, '%d-%m-%Y'))
ORDER BY EndingYear;

       
       
       
       
       




